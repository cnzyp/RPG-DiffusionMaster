# Nothing else from `mid` survives: \title, \author, \maketitle and the CVPR
# comment banners are all replaced by the frontmatter above.
def build(anonymous, verbose=True):
    """The manuscript, with or without anything that identifies the authors."""
    out = (PREAMBLE.replace('%%EXTERNALDOC%%',
                            '\\usepackage{xr}\n\\externaldocument{supp_pr}')
           + front(anonymous) + '\n' + teaser + '\n\n' + body)

    # ---------------------------------------------------------- transformations --
    def swap(old, new, label, expect=None):
        """Rewrite every occurrence; return how many there were.

        Counts that relocation changes are checked relatively -- what has to
        hold is that a paired environment opens and closes the same number of
        times, and that nothing matched zero.
        """
        nonlocal out
        n = out.count(old)
        assert n > 0, f'{label}: matched nothing'
        if expect is not None:
            assert n == expect, f'{label}: expected {expect}, found {n}'
        out = out.replace(old, new)
        if verbose: print(f'ok: {label} ({n})')
        return n


    # Pull the marked blocks out, in order, leaving a sentence behind.
    global SUPP_BODY
    supp, n = [], 0
    while '%%SUPP{' in out:
        i = out.index('%%SUPP{')
        sid = out[i + 7:out.index('}', i)]
        j = out.index('%%ENDSUPP', i)
        block = out[out.index('\n', i) + 1:j].rstrip()
        # A block that contains another marker means the two overlap: the
        # inner one would be removed silently and its content left behind.
        assert '%%SUPP{' not in block, f'{sid}: block contains another marker'
        n += 1
        # A whole subsection brings its own heading; a loose paragraph needs
        # one, and SUPP_TITLES supplies it.
        if block.lstrip().startswith('\\subsection{'):
            block = block.replace('\\subsection{', '\\section{', 1)
        else:
            block = '\\section{' + SUPP_TITLES[sid] + '}\n' + block
        supp.append(block)
        out = (out[:i] + SUPP_POINTERS[sid].replace('<<N>>', str(n))
               + '\n' + out[j + len('%%ENDSUPP'):])
    if verbose and supp:
        print(f'ok: {n} subsections moved to supplementary material')

    n_open = swap(r'\begin{figure*}', r'\begin{figure}', 'figure* -> figure')
    n_close = swap(r'\end{figure*}', r'\end{figure}', 'figure* -> figure (close)')
    assert n_open == n_close, f'figure*: {n_open} opened, {n_close} closed'
    # Float placement.  Six figures are written [H] and all six land where they
    # are written; every [t] and [htbp] figure instead jams the float queue and
    # flushes at the final \clearpage -- figures 2, 5, 8, 9, 11 and 13 all came
    # out on pages 98-103 of a 103-page draft, tens of pages after the text that
    # discusses them.  The 19 tables are [htbp] too and place correctly, so it is
    # the figures' size that jams the queue, not the specifier by itself.  Pin
    # them where they are written; a figure that will not fit the remaining space
    # starts a new page, which is what a reader wants anyway.
    swap('\\begin{figure}[t]', '\\begin{figure}[H]', 'figures pinned in place')
    swap('\\begin{figure}[htbp]', '\\begin{figure}[H]', 'figures pinned in place')

    swap('\\resizebox{\\columnwidth}{!}{%', '\\fitbox{%',
         'tables refit to the text block')
    # A figure sized to \linewidth in one column can be taller than the page it
    # has to share with its caption; cap the height without stretching anything.
    swap('\\includegraphics[width=\\linewidth]',
         '\\includegraphics[width=\\linewidth,max totalheight=0.62\\textheight]',
         'figures capped in height')

    # Bibliography: drop the {\small ...} wrapper the two-column layout needed.
    OLD_BIB = '{\\small\n\\bibliographystyle{ieeetr}\n\\bibliography{refs}\n}'
    NEW_BIB = (declarations(anonymous).strip() + '\n\n% ' + '=' * 60 +
               '\n\\bibliographystyle{elsarticle-num}\n\\bibliography{refs}')
    assert out.count(OLD_BIB) == 1, 'bibliography block not matched'
    out = out.replace(OLD_BIB, NEW_BIB)
    if verbose: print('ok: elsarticle-num bibliography + declarations')

    # tab:main carries ~60 lines of per-baseline protocol in its caption.  Two
    # columns could give that a page of its own; one column at 12pt cannot fit it
    # above the table it describes, and the float overruns the page.  The
    # per-baseline notes move below the float, which is where a journal would set
    # them anyway.  Everything that reads as caption stays in the caption.
    MARK = "  $\\dagger$: Conceptrol~\\cite{he2025conceptrol}"
    i = out.index('\\caption{%\n  \\textbf{Comparison on Mixed-Eval-v1}')
    j, depth = out.index('{', i), 0
    while True:                                     # matching brace of \caption{
        if out[j] == '{':
            depth += 1
        elif out[j] == '}':
            depth -= 1
            if depth == 0:
                break
        j += 1
    caption = out[i:j + 1]
    assert caption.count(MARK) == 1, 'tab:main notes marker not found'
    kept, notes = caption.split(MARK, 1)
    notes = MARK + notes[:-1].rstrip()              # drop the caption's close brace

    n += 1
    supp.append('\\section{' + SUPP_TITLES['tabnotes'] + '}\n'
                + '\\noindent\n' + notes.lstrip())
    out = (out[:i] + kept.rstrip()
           + '\n  The configuration of each baseline is given in '
             f'Supplementary~S{n}.\n}}'
           + out[j + 1:])
    if verbose: print('ok: tab:main notes moved to supplementary material')

    if supp:
        SUPP_BODY = '\n\n'.join(supp)

    for stale in ['\\usepackage{cvpr}', '\\cvprfinalcopy', '\\maketitle',
                  '\\begin{figure*}', '\\resizebox{\\columnwidth}']:
        assert stale not in out, f'CVPR leftover survived: {stale}'


    return out


