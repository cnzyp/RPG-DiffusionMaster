targets = [(DST, True, True)]
if args.named:
    targets.append((Path('paper_latex/main_pr_named.tex'), False, False))
for path, anon, verbose in targets:
    text = build(anon, verbose)
    path.write_bytes(text.replace('\n', '\r\n').encode('utf-8'))
    kind = 'blind' if anon else 'named'
    print(f'written {path} ({len(text.splitlines())} lines, {kind})')

# The supplementary document reuses the manuscript's preamble so the two are
# typeset identically, then renumbers everything S1, S2, ...  Blocks moved out
# still cite the manuscript's sections and tables, and the manuscript cites
# theirs, so both read the other's .aux through xr: build main, supp, main,
# supp.
if SUPP_BODY:
    head = PREAMBLE[:PREAMBLE.index(r"\begin{document}")].replace(
        "%%EXTERNALDOC%%",
        "\\usepackage{xr}\n\\externaldocument{main_pr}")
    supp = (head
            + SUPP_PREAMBLE_TAIL
            + "\\linenumbers\n\n"
            + SUPP_BODY
            + "\n\n% " + "=" * 60
            + "\n\\bibliographystyle{elsarticle-num}\n\\bibliography{refs}\n"
            + "\n\\end{document}\n")
    sp = Path("paper_latex/supp_pr.tex")
    sp.write_bytes(supp.replace("\n", "\r\n").encode("utf-8"))
    print(f"written {sp} ({len(supp.splitlines())} lines)")
